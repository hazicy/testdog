import type { RunArtifact } from '@/workspace/types';

export const statuses = {
  queued: '排队中',
  preparing: '准备中',
  finalizing: '归档中',
  running: '执行中',
  passed: '已通过',
  failed: '失败',
  cancelled: '已停止',
};
export const time = (ms: number) =>
  `${Math.floor(ms / 60000)
    .toString()
    .padStart(2, '0')}:${Math.floor((ms / 1000) % 60)
    .toString()
    .padStart(2, '0')}`;
export const asset = (runId: string, artifact: RunArtifact) =>
  `/api/runs/${runId}/artifacts/${artifact.id}`;
